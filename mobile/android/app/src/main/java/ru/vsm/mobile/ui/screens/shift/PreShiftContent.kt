private fun assignmentStep(cls: CarClass, rand: ShiftRng): DialogNode {
    val variant = rand.pick(listOf("car", "train", "stops"))
    if (variant == "train") {
        data class T(val id: String, val text: String, val right: Boolean)
        val opts = listOf(
            T("t1", "Поезд 752, отправление 07:40, путь третий.", true),
            T("t2", "Поезд 754, отправление 09:40.", false),
            T("t3", "Уточню у коллег на перроне.", false),
        )
        return DialogNode(
            id = "assignment", speaker = "chief", speakerOverride = CHIEF,
            context = "Инструктаж у начальника поезда. В наряде: поезд № 752, отправление 07:40, путь 3.",
            text = "Какой у нас сегодня поезд и откуда отправляемся?",
            choices = opts.map { o ->
                c(o.id, o.text, if (o.right) 4 else -6, 0,
                    if (o.right) "Верно. Посадка за 20 минут до отправления." else "Нет — № 752, 07:40, третий путь. Сверяйтесь с нарядом.",
                    "Проводник знает номер поезда, время и путь отправления до выхода на перрон — пассажиры спрашивают об этом первыми.")
            },
        )
    }
    if (variant == "stops") {
        data class S(val id: String, val text: String, val right: Boolean)
        val opts = listOf(
            S("s1", "Тверь и Великий Новгород, конечная — Санкт-Петербург.", true),
            S("s2", "Без остановок до Санкт-Петербурга.", false),
            S("s3", "Бологое и Тверь.", false),
        )
        return DialogNode(
            id = "assignment", speaker = "chief", speakerOverride = CHIEF,
            context = "Инструктаж у начальника поезда. В наряде — остановки Тверь и Великий Новгород.",
            text = "Где у нас остановки по пути?",
            choices = opts.map { o ->
                c(o.id, o.text, if (o.right) 4 else -6, 0,
                    if (o.right) "Верно. Предупреждайте выходящих заранее." else "Нет: Тверь и Великий Новгород. Выходящих предупреждаем за 10–15 минут.",
                    "Проводник заранее знает остановки: он предупреждает выходящих пассажиров и следит за посадкой.")
            },
        )
    }
    val titles = mapOf(
        DomainCarClass.STANDARD to ("Стандарт" to 5),
        DomainCarClass.COMFORT to ("Комфорт" to 4),
        DomainCarClass.BUSINESS to ("Бизнес" to 2),
        DomainCarClass.FIRST to ("Первый" to 1),
    )
    val (ownTitle, ownCar) = titles.entries.first { it.key.name == cls.key }.value
    val right = c("k0", "Вагон $ownCar, класс «$ownTitle».", 4, 0, "Верно. Удачного рейса.", "Проводник знает свой вагон и класс до выхода на перрон.")
    val others = titles.entries.filter { it.key.name != cls.key }.shuffled().take(2).mapIndexed { i, e ->
        val (t, car) = e.value
        c("k${i + 1}", "Вагон $car, класс «$t».", -6, 0, "Нет — вагон $ownCar, «$ownTitle». Сверяйтесь с нарядом.", "Проводник знает свой вагон и класс до выхода на перрон.")
    }
    return DialogNode(
        id = "assignment", speaker = "chief", speakerOverride = CHIEF,
        context = "Инструктаж у начальника поезда.",
        text = "Напомните, где вы сегодня работаете?",
        choices = (listOf(right) + others).shuffled(),
    )
}

/** Собрать шаги заступа для смены: самочувствие -> наряд -> готовность -> (иногда) особое указание. */
fun buildPreShift(cls: CarClass, rand: ShiftRng, forceNotice: Boolean? = null): DialogScript {
    val health = rand.pick(HEALTH_POOL).copy(id = "health")
    val readiness = rand.pick(READINESS_POOL).copy(id = "readiness")
    val steps = mutableListOf(health, assignmentStep(cls, rand), readiness)
    val withNotice = forceNotice ?: (rand.next() < 0.7)
    if (withNotice) steps.add(rand.pick(NOTICE_POOL).copy(id = "notice"))
    return linearScript(steps)
}
