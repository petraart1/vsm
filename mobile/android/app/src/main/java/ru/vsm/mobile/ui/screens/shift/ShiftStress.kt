/** Вероятность «проблемного» заступа — примерно каждая четвёртая смена. */
fun rollCondition(rand: ShiftRng, rate: Double = 0.25): MedCondition {
    val r = rand.next()
    return when {
        r < rate * 0.4 -> MedCondition.FEVER
        r < rate * 0.72 -> MedCondition.ALCOHOL
        r < rate -> MedCondition.SUBSTANCES
        else -> MedCondition.FIT
    }
}
