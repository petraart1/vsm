/** Собрать шаги заступа для смены: самочувствие → наряд → готовность → (иногда) особое указание. */
export function buildPreShift(cls, rand, opts = {}) {
  const health = opts.health ? HEALTH.find((h) => h.key === opts.health) || pick(rand, HEALTH) : pick(rand, HEALTH);
  const readiness = pick(rand, READINESS);
  const steps = [
    { id: "health", speaker: "medic", context: health.context, text: "Доброе утро. Как самочувствие, жалобы есть?", choices: health.choices },
    assignmentStep(cls, rand),
    { id: "readiness", speaker: "chief", context: readiness.context, text: readiness.text, choices: readiness.choices }
  ];
  const withNotice = opts.notice === true || (opts.notice !== false && rand() < 0.7);
  if (withNotice) {
    const n = pick(rand, NOTICES);
    steps.push({ id: "notice", speaker: "chief", context: n.context, text: n.text, choices: n.choices });
  }
  return steps;
}

export const PRE_SHIFT_VARIANTS = { health: HEALTH.length, readiness: READINESS.length, notices: NOTICES.length };
