function assignmentStep(cls, rand) {
  const variant = pick(rand, ["car", "train", "stops"]);
  if (variant === "train") {
    const choices = [
      { id: "t1", text: "— Поезд 752, отправление 07:40, путь третий.", right: true },
      { id: "t2", text: "— Поезд 754, отправление 09:40.", right: false },
      { id: "t3", text: "— Уточню у коллег на перроне.", right: false }
    ];
    return {
      id: "assignment",
      speaker: "chief",
      context: "Инструктаж у начальника поезда. В наряде: поезд № 752, отправление 07:40, путь 3.",
      text: "Какой у нас сегодня поезд и откуда отправляемся?",
      choices: choices.map((c) => ({ id: c.id, text: c.text, safety: c.right ? 4 : -6, loyalty: 0, best: c.right, reply: c.right ? "Верно. Посадка за 20 минут до отправления." : "Нет — № 752, 07:40, третий путь. Сверяйтесь с нарядом.", note: "Проводник знает номер поезда, время и путь отправления до выхода на перрон — пассажиры спрашивают об этом первыми." }))
    };
  }
  if (variant === "stops") {
    const choices = [
      { id: "s1", text: "— Тверь и Великий Новгород, конечная — Санкт-Петербург.", right: true },
      { id: "s2", text: "— Без остановок до Санкт-Петербурга.", right: false },
      { id: "s3", text: "— Бологое и Тверь.", right: false }
    ];
    return {
      id: "assignment",
      speaker: "chief",
      context: "Инструктаж у начальника поезда. В наряде — остановки Тверь и Великий Новгород.",
      text: "Где у нас остановки по пути?",
      choices: choices.map((c) => ({ id: c.id, text: c.text, safety: c.right ? 4 : -6, loyalty: 0, best: c.right, reply: c.right ? "Верно. Предупреждайте выходящих заранее." : "Нет: Тверь и Великий Новгород. Выходящих предупреждаем за 10–15 минут.", note: "Проводник заранее знает остановки: он предупреждает выходящих пассажиров и следит за посадкой." }))
    };
  }
  const options = CLASS_ORDER.map((k, i) => {
    const c = CAR_CLASSES[k];
    const right = k === cls.key;
    return { id: `k${i}`, text: `— Вагон ${c.car}, класс «${c.title}».`, safety: right ? 4 : -6, loyalty: 0, best: right, reply: right ? "Верно. Удачного рейса." : `Нет — вагон ${cls.car}, «${cls.title}». Сверяйтесь с нарядом.`, note: "Проводник знает свой вагон и класс до выхода на перрон." };
  });
  const right = options.find((o) => o.best);
  const others = options.filter((o) => !o.best).sort(() => rand() - 0.5).slice(0, 2);
  return { id: "assignment", speaker: "chief", context: "Инструктаж у начальника поезда.", text: "Напомните, где вы сегодня работаете?", choices: [right, ...others] };
}

