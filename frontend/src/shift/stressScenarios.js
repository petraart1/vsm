/** Вероятность «проблемного» заступа — примерно каждая четвёртая смена. */
export function rollCondition(rand, rate = 0.25) {
  const r = rand();
  if (r < rate * 0.4) return "fever";
  if (r < rate * 0.72) return "alcohol";
  if (r < rate) return "substances";
  return "fit";
}

