export function localVerdict(log) {
  if (log.some((l) => l.critical)) return "Критическая ошибка безопасности";
  const safety = log.reduce((a, l) => a + l.safety, 0);
  const loyalty = log.reduce((a, l) => a + l.loyalty, 0);
  const allBest = log.every((l) => l.best);
  if (allBest || (safety >= 20 && loyalty >= 0)) return "Хорошо справились";
  return "Есть над чем поработать";
}

/** Перемешать варианты ответа детерминированно (чтобы правильный не был всегда первым). */
export function shuffled(list, seed) {
  const a = list.slice();
  let s = seed || 1;
  for (let i = a.length - 1; i > 0; i -= 1) {
    s = (s * 16807) % 2147483647;
    const j = s % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
